// MC-1576: how pool changes are approved, the user's choice at setup (policy.json approvePoolChanges):
// - 'within-caps' (the default; a policy from before it too): a plan within the policy applies without approval, unless
//   it brings new content for the clean state every lease starts from: an image no approved plan has built from, a
//   guest setup script, or a ready-made disk (ready.test.js). Resizes, network modes, removals, refreshes and pool
//   checkpoints apply as planned;
// - 'each': every plan approved (approvals.test.js covers the approval itself).
// Either way: the caps are checked again at apply; the decision is made at apply from the policy and the journal (never
// from what the plan's text said); a plan applies once, also after a restart; a check alone, or a job within the caps,
// never makes an image approved; the images of VMs already in the pool count as approved, once, at the first start.
const test = require('node:test')
const assert = require('assert')
const fs = require('fs')
const path = require('path')
const { T, scratch, startHelper, approve, seedImage, waitFor, withPool } = require('./helpers')

const req = (c, op, args) => c.request(op, args).then(r => r, e => ({ error: e.message, text: e.message }))
const status = async c => (await c.request('status')).text
const SEED = 'ab'.repeat(32)
const setPolicy = (sc, fn) => { const f = path.join(sc.stateDir, 'policy.json'); const p = JSON.parse(fs.readFileSync(f, 'utf8')); fn(p); fs.writeFileSync(f, JSON.stringify(p)) }
const jobs = sc => sc.journal().filter(r => r.t === 'job')
const approvedImages = sc => sc.journal().filter(r => r.t === 'image-approved').map(r => r.sha256)
async function waitJob(c, op) {
  await waitFor(async () => new RegExp(`Last pool job: ${op} (finished|FAILED)`).test(await status(c)), T.poolJobMs, `the ${op} job`)
  return (await status(c)).split('\n').find(l => l.startsWith('Last pool job'))
}

test('within-caps: a checked image needs approval until a plan the user approved builds from it; then resizes apply as planned, also after a restart', async t => {
  const sc = scratch('mode-image', { policy: { maxVms: 4 } })
  let h = await startHelper(sc); await h.stop()
  seedImage(sc) // checked, never approved
  h = await startHelper(sc)
  t.after(() => h.stop())
  const admin = h.conn(1)
  assert.match(await status(admin), /pool changes within these caps apply without approval/)
  const p1 = await admin.request('pool_plan', { action: 'create', vms: 1, cores: 2, memoryGB: 4, image: SEED })
  assert.match(p1.text, /It needs the user's approval: a new image: no plan you approved has built from it\./)
  assert.match((await req(admin, 'pool_create', { planId: p1.data.planId })).text, /is not approved/)
  assert.deepStrictEqual(approvedImages(sc), [], 'a check alone approves nothing')
  approve(sc, p1.data.planId)
  assert.match((await admin.request('pool_create', { planId: p1.data.planId })).text, /^Approved plan p-\w+ accepted/)
  assert.match(await waitJob(admin, 'create'), /create finished/)
  assert.deepStrictEqual(approvedImages(sc), [SEED])
  // Grow: the same image, within the caps: no approval.
  const p2 = await admin.request('pool_plan', { action: 'resize', vms: 2 })
  assert.match(p2.text, /within the policy's caps, and setup lets those apply without approval .*call pool_resize\(\{ planId: "p-\w+" \}\)/)
  assert.doesNotMatch(p2.text, /approve\.cmd/)
  assert.match((await admin.request('pool_resize', { planId: p2.data.planId })).text, /^Plan p-\w+ accepted \(within the policy's caps: no approval needed\)/)
  assert.match(await waitJob(admin, 'resize'), /resize finished/)
  const j = jobs(sc).at(-1)
  assert.deepStrictEqual([j.planId, j.approval, j.nonce], [p2.data.planId, 'caps', undefined])
  assert.deepStrictEqual(approvedImages(sc), [SEED], 'a job within the caps adds no approval')
  // Still within the caps after a restart; the applied plan can't be applied again.
  await h.stop()
  h = await startHelper(sc)
  const a2 = h.conn(1)
  assert.match((await req(a2, 'pool_resize', { planId: p2.data.planId })).text, /Plan p-\w+ was already applied: make a new plan\./)
  const p3 = await a2.request('pool_plan', { action: 'resize', vms: 1, network: 'host' })
  assert.match(p3.text, /within the policy's caps/)
  assert.match((await a2.request('pool_resize', { planId: p3.data.planId })).text, /accepted \(within the policy's caps/)
  assert.match(await waitJob(a2, 'resize'), /resize finished/)
  await h.stop()
})

test('within-caps: a plan applies once, also when applied twice at once; a failed one too', async t => {
  const sc = scratch('mode-once', { policy: { maxVms: 4 } })
  const { h, admin } = await withPool(sc, 1)
  t.after(() => h.stop())
  const p = await admin.request('pool_plan', { action: 'resize', vms: 2 })
  const both = await Promise.all([req(admin, 'pool_resize', { planId: p.data.planId }), req(h.conn(2), 'pool_resize', { planId: p.data.planId })])
  assert.strictEqual(both.filter(r => /accepted/.test(r.text)).length, 1, both.map(r => r.text).join(' | '))
  assert.match(both.find(r => !/accepted/.test(r.text)).text, /already applied|A pool job is already running/)
  await waitJob(admin, 'resize')
  assert.match((await req(admin, 'pool_resize', { planId: p.data.planId })).text, /was already applied/)
  assert.strictEqual(jobs(sc).filter(j => j.planId === p.data.planId).length, 1)
  assert.strictEqual(Object.keys(sc.stub().vms).length, 2, 'one creation')
  // A failed job's plan is used up too.
  const pf = await admin.request('pool_plan', { action: 'resize', vms: 3 })
  sc.patchStub(s => { s.fail = { ...(s.fail || {}), 'create-vm': 1 } })
  await admin.request('pool_resize', { planId: pf.data.planId })
  assert.match(await waitJob(admin, 'resize'), /FAILED/)
  assert.match((await req(admin, 'pool_resize', { planId: pf.data.planId })).text, /was already applied/)
})

test('decided at apply: a within-caps plan, then setup switched to Each, needs approval; a cap or network ceiling lowered before apply refuses it', async t => {
  const sc = scratch('mode-apply', { policy: { maxVms: 4 } })
  const { h, admin } = await withPool(sc, 1)
  t.after(() => h.stop())
  const p = await admin.request('pool_plan', { action: 'resize', vms: 2 })
  assert.match(p.text, /within the policy's caps/)
  setPolicy(sc, x => { x.approvePoolChanges = 'each' })
  await h.stop()
  let h2 = await startHelper(sc)
  let a = h2.conn(1)
  assert.match(await status(a), /pool changes each approved by the user \(setup chose Each\)/)
  assert.match((await req(a, 'pool_resize', { planId: p.data.planId })).text, /Plan p-\w+ is not approved/)
  const pe = await a.request('pool_plan', { action: 'resize', vms: 2 })
  assert.match(pe.text, /Nothing is changed until the user approves this exact plan/)
  assert.doesNotMatch(pe.text, /It needs the user's approval:/)
  await h2.stop()
  // Back to within-caps; the plan's cap and network ceiling then lowered under it.
  setPolicy(sc, x => { x.approvePoolChanges = 'within-caps' })
  h2 = await startHelper(sc); a = h2.conn(1)
  const pv = await a.request('pool_plan', { action: 'resize', vms: 2 })
  const pn = await a.request('pool_plan', { action: 'resize', vms: 1, network: 'internet' })
  await h2.stop()
  setPolicy(sc, x => { x.maxVms = 1; x.maxNetwork = 'host' })
  h2 = await startHelper(sc); a = h2.conn(1)
  t.after(() => h2.stop())
  assert.match((await req(a, 'pool_resize', { planId: pv.data.planId })).text, /outside the policy now: 2 VMs is more than the policy's 1/)
  assert.match((await req(a, 'pool_resize', { planId: pn.data.planId })).text, /outside the policy now: .*internet/)
  assert.strictEqual(Object.keys(sc.stub().vms).length, 1, 'nothing changed')
})

test('within-caps: a guest setup script still needs approval; a refresh and a removal apply as planned', async t => {
  const sc = scratch('mode-kinds', { policy: { maxVms: 4 } })
  const { h, admin } = await withPool(sc, 1)
  t.after(() => h.stop())
  const f = path.join(sc.dir, 'user', 'guest.ps1'); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, 'Write-Output hi')
  const ps = await admin.request('pool_plan', { action: 'resize', vms: 2, guestScript: f })
  assert.match(ps.text, /It needs the user's approval: a guest setup script\./)
  assert.match((await req(admin, 'pool_resize', { planId: ps.data.planId })).text, /is not approved/)
  const [v1] = [...(await status(admin)).matchAll(/^- (hvmcp-[0-9a-f]+):/gm)].map(m => m[1])
  const pr = await admin.request('pool_plan', { action: 'refresh-clean', targets: [v1] })
  assert.match(pr.text, /within the policy's caps.*pool_refresh/)
  assert.match((await admin.request('pool_refresh', { planId: pr.data.planId })).text, /accepted \(within the policy's caps/)
  assert.match(await waitJob(admin, 'refresh'), /refresh finished/)
  const pd = await admin.request('pool_plan', { action: 'remove' })
  assert.match((await admin.request('pool_remove', { planId: pd.data.planId })).text, /accepted \(within the policy's caps/)
  assert.match(await waitJob(admin, 'remove'), /remove finished/)
  assert.deepStrictEqual(sc.stub().vms, {})
})

test('within-caps: a pool checkpoint is published and removed as planned', async t => {
  const sc = scratch('mode-pcp', { policy: { maxVms: 4 } })
  const { h } = await withPool(sc, 1)
  await h.stop()
  const h2 = await startHelper(sc, T.profile('queue'))
  t.after(() => h2.stop())
  const a = h2.conn(1)
  const roots = [path.join(sc.dir, 'work')]; fs.mkdirSync(roots[0], { recursive: true })
  const got = await a.request('acquire', { minutes: 30, roots })
  const vm = got.text.match(/^Leased (hvmcp-\w+)/)[1]
  await a.request('start', {})
  const p = await a.request('pool_plan', { action: 'checkpoint', roots, name: 'tools', targets: [vm] })
  assert.match(p.text, /within the policy's caps.*pool_checkpoint/)
  assert.match((await a.request('pool_checkpoint', { planId: p.data.planId })).text, /published "tools"/)
  assert.match((await req(a, 'pool_checkpoint', { planId: p.data.planId })).text, /was already applied/)
  await a.request('release')
  const pr = await a.request('pool_plan', { action: 'checkpoint-remove', roots, name: 'tools', targets: [vm] })
  assert.match(pr.text, /within the policy's caps/)
  assert.match((await a.request('pool_checkpoint', { planId: pr.data.planId })).text, /- hvmcp-\w+: retired and removed/)
  assert.ok(jobs(sc).filter(j => j.op === 'checkpoint').every(j => j.approval === 'caps'))
})

test('the first start with approvals within the caps: the images of the VMs then in the pool count as approved, once; a checked-only image doesn\'t', async t => {
  const sc = scratch('mode-migrate', { policy: { maxVms: 4 } })
  const { h } = await withPool(sc, 1)
  await h.stop()
  // As a journal from before MC-1576: no image-approved or approvals-migrated records; plus a second, checked-only image.
  const jf = path.join(sc.stateDir, 'journal.jsonl')
  const other = 'cd'.repeat(32)
  const lines = fs.readFileSync(jf, 'utf8').trim().split('\n').filter(l => !/"t":"(image-approved|approvals-migrated)"/.test(l))
  const img = JSON.parse(lines.find(l => l.includes('"t":"image"')))
  fs.writeFileSync(path.join(path.dirname(img.file), `${other}.iso`), 'iso2')
  lines.push(JSON.stringify({ ...img, sha256: other, file: path.join(path.dirname(img.file), `${other}.iso`), seq: 5000 }))
  fs.writeFileSync(jf, lines.join('\n') + '\n')
  let h2 = await startHelper(sc)
  await h2.stop()
  assert.deepStrictEqual(approvedImages(sc), [SEED])
  assert.strictEqual(sc.journal().filter(r => r.t === 'approvals-migrated').length, 1)
  h2 = await startHelper(sc)
  t.after(() => h2.stop())
  assert.strictEqual(sc.journal().filter(r => r.t === 'approvals-migrated').length, 1, 'once')
  const a = h2.conn(1)
  assert.match((await a.request('pool_plan', { action: 'resize', vms: 2, image: SEED })).text, /within the policy's caps/)
  assert.match((await a.request('pool_plan', { action: 'resize', vms: 2, image: other })).text, /It needs the user's approval: a new image/)
})
